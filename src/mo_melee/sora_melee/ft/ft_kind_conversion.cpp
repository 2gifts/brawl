// Writes the fighter kinds of a character kind to out and returns how many there are.
u8 ftKindConversion::convertKind(gmCharacterKind characterKind, ftKind* out) {
    ftKindConversionEntry entry = s_kindTable[characterKind];
    u8 count = 0;
    for (int i = 0; i < 4; i++) {
        if (entry.m_kinds[i] != -1) {
            out[count++] = static_cast<ftKind>(entry.m_kinds[i]);
        }
    }
    return count;
}
